    check('script-failure fallback shows all eight pages in order',not fallback['enhanced'] and [x['id'] for x in fallback['pages']]==list(map(str,range(8))) and all(x['display']!='none' for x in fallback['pages']) and fallback['controls']=='none' and [x['top'] for x in fallback['pages']]==sorted(x['top'] for x in fallback['pages']),fallback)
