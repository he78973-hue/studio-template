#!/usr/bin/env python3
"""Browser acceptance through the approved agent-browser CLI, not an alternate driver."""
from pathlib import Path
import json, os, subprocess, time
ROOT=Path(__file__).resolve().parents[1]
BASE=os.environ.get('BAUHAUS_BASE','http://127.0.0.1:8876/').rstrip('/')+'/'
(ROOT/'qa').mkdir(exist_ok=True)
CDP=os.environ.get('BAUHAUS_CDP','http://127.0.0.1:9223')
CLI=['agent-browser','--session','bauhaus-prototype']
results=[]
def run(*args):
    r=subprocess.run(CLI+list(map(str,args)),capture_output=True,text=True,timeout=25)
    if r.returncode:raise RuntimeError(f'{args[0]}: {r.stderr or r.stdout}')
    return r.stdout.strip()
def ev(expression):
    value=json.loads(run('eval',expression))
    return json.loads(value) if isinstance(value,str) else value
def check(name,condition,detail=None):
    results.append({'test':name,'passed':bool(condition),'detail':detail})
    (ROOT/'qa/browser-results.json').write_text(json.dumps(results,ensure_ascii=False,indent=2))
    print(('PASS ' if condition else 'FAIL ')+name,flush=True)
    assert condition,(name,detail)
def state():return ev('JSON.stringify(BauhausBook.getState())')
def capture(name,full=False):
    args=['screenshot']+(['--full'] if full else [])+[str(ROOT/'qa'/name)]
    return run(*args)
