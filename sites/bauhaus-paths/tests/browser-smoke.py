    metrics=ev('JSON.stringify({w:innerWidth,scroll:document.documentElement.scrollWidth,pages:[...document.querySelectorAll("[data-page]")].filter(e=>getComputedStyle(e).display!=="none").map(e=>e.dataset.page),size:getComputedStyle(document.querySelector(".school-story>p:not(.chapter-marker)")).fontSize})')
