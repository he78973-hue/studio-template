    run('set','viewport',1440,900)
    available=ev('JSON.stringify(!!document.querySelector("#object-canvas").getContext("webgl2")?.getExtension("WEBGL_lose_context"))')
    if available:
        ev('JSON.stringify(document.querySelector("#object-canvas").getContext("webgl2").getExtension("WEBGL_lose_context").loseContext())')
        time.sleep(.1)
        run('click','[data-select="chess"]')
