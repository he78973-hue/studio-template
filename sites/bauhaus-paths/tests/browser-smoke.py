    check('initial spread and boundaries',ev('JSON.stringify({s:BauhausBook.getState().committed,p:document.querySelector("#previous").disabled,n:document.querySelector("#next").disabled})')=={'s':0,'p':True,'n':False})
    run('click','#next');time.sleep(.8)
    check('button forward and URL',state()['committed']==1 and ev('JSON.stringify(location.hash)')=='#spread-2')
