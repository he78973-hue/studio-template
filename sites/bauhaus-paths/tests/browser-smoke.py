        current=ev('JSON.stringify({state:BauhausObjects.getState(),selected:document.querySelector("[aria-pressed=true][data-select]").dataset.select,visible:[...document.querySelectorAll(".object-note")].filter(e=>getComputedStyle(e).display!=="none").map(e=>e.dataset.note)})')
