    controls=ev('JSON.stringify({font:parseFloat(getComputedStyle(document.querySelector(".viewer-instruction")).fontSize),icon:document.querySelector("#object-reset svg")?.getAttribute("viewBox"),hidden:document.querySelector("#object-reset svg")?.getAttribute("aria-hidden"),height:document.querySelector("#object-reset").getBoundingClientRect().height})')
